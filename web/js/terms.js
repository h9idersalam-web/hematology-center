// المصطلحات المعتمدة في الواجهة (بقرار صاحب المشروع، 7 تشرين الثاني 2026):
//   «الدورة» ← «الجرعة»، و«جرعة الدواء» ← «الجرعة الدوائية»، و«خارج المرجع» ← «خارج الحد الطبيعي».
// تُطبَّق على النصوص الآتية من قاعدة البيانات (رسائل الخطأ والإشعارات وأسباب التعليق)،
// لأن نصوص الواجهة نفسها كُتبت بالمصطلحات الجديدة مباشرة.
const DOSE = [
  [/والجرعات/g, 'و§1'], [/الجرعات/g, '§1'], [/وجرعاتها/g, 'و§2'], [/جرعاتها/g, '§2'], [/وجرعات/g, 'و§3'], [/جرعات/g, '§3'],
  [/والجرعة/g, 'و§4'], [/للجرعة/g, 'ل§5'], [/الجرعة/g, '§4'], [/وجرعته/g, 'و§6'], [/جرعتان/g, '§7'], [/جرعة/g, '§8'],
];
const OUT = { '§1': 'الجرعات الدوائية', '§2': 'جرعاتها الدوائية', '§3': 'جرعات دوائية', '§4': 'الجرعة الدوائية',
  '§5': 'لجرعة الدوائية', '§6': 'جرعته الدوائية', '§7': 'جرعتان دوائيتان', '§8': 'جرعة دوائية' };

export function terms(s) {
  if (!s || typeof s !== 'string' || !/[؀-ۿ]/.test(s)) return s;
  // رقم الدورة بالإنكليزية: «الدورة 3» ← «Cycle 3» (بقرار صاحب المشروع)
  let t = s.replace(/(?:ال)?دورة\s*(\d+)/g, 'Cycle $1').replace(/خارج المرجع/g, 'خارج الحد الطبيعي');
  for (const [re, ph] of DOSE) t = t.replace(re, ph);
  t = t.replace(/دورات/g, 'جرعات').replace(/دورة/g, 'جرعة').replace(/دورت/g, 'جرعت');
  return t.replace(/§\d/g, (m) => OUT[m]);
}
